/**
 * Downloads the Public Suffix List and writes extension/core/psl-data.js.
 *
 * The list tells which part of a host name is a public suffix ("co.jp",
 * "github.io"), so Q-Fill can compare registrable domains: bank.co.jp and
 * evil.co.jp are different sites even though both end in .co.jp.
 *
 * The extension never fetches the list at run time. Run this script by hand
 * to refresh the bundled copy, then review the diff:
 *
 *   node scripts/update-psl.mjs
 *
 * The list is published by Mozilla under the Mozilla Public License 2.0.
 */
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const SOURCE = 'https://publicsuffix.org/list/public_suffix_list.dat';
const OUT = fileURLToPath(new URL('../extension/core/psl-data.js', import.meta.url));

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`Could not download the list: ${response.status}`);
const text = await response.text();
if (!text.includes('===BEGIN ICANN DOMAINS===') || !text.includes('===BEGIN PRIVATE DOMAINS===')) {
  throw new Error('The download does not look like the Public Suffix List');
}

/** Converts one rule to the ASCII (punycode) form that URL.hostname uses. */
function toAscii(rule) {
  const exception = rule.startsWith('!');
  const body = exception ? rule.slice(1) : rule;
  const labels = body.split('.').map(label => {
    if (label === '*') return '*';
    const host = new URL(`http://${label}.invalid`).hostname;
    return host.slice(0, -'.invalid'.length);
  });
  return (exception ? '!' : '') + labels.join('.');
}

const rules = new Set();
for (const raw of text.split('\n')) {
  const line = raw.trim().split(/\s/)[0];
  if (!line || line.startsWith('//')) continue;
  rules.add(toAscii(line.toLowerCase()));
}
if (rules.size < 5000) throw new Error(`Only ${rules.size} rules, refusing to write`);

const date = new Date().toISOString().slice(0, 10);
const body = `/**
 * Public Suffix List, ASCII form, one rule per line. Generated by
 * scripts/update-psl.mjs on ${date} from ${SOURCE}
 *
 * This Source Code Form is subject to the terms of the Mozilla Public
 * License, v. 2.0. If a copy of the MPL was not distributed with this file,
 * You can obtain one at https://mozilla.org/MPL/2.0/.
 */
export const PSL_RULES = ${JSON.stringify([...rules].join('\n'))};
`;
await writeFile(OUT, body);
console.log(`Wrote ${rules.size} rules to ${OUT}`);
